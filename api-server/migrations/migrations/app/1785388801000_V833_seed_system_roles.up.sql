-- V796: Seed built-in roles as read-only "system" custom_roles with predefined
-- (module × class) permission grants.
--
-- The 4 built-in roles the product exposes (tenant_admin, tenant_admin_readonly,
-- account_admin, account_admin_readonly) — plus super_admin* and
-- k8s_namespace_admin* for model completeness — are seeded as immutable
-- custom_roles (is_system=true, tenant_id NULL = global). Their grants mirror
-- each role's actions.yaml operation surface. These rows are READ-ONLY: the
-- customrole service rejects CRUD on is_system roles, and they are hidden from
-- the tenant-scoped CRUD queries (tenant_id NULL).
--
-- Additive + reversible; no code reads is_system for enforcement yet (the
-- unified resolver is a later change). The grant rows in section 3 are GENERATED
-- from app/src/lib/systemRoleGrants.ts and guarded by
-- app/src/lib/__tests__/systemRoleGrants.test.ts (CI fails if actions.yaml
-- drifts from the seeded grants — regenerate this block if so).

-- 1. custom_roles: allow global system roles (tenant_id NULL) + system flags.
ALTER TABLE "public"."custom_roles"
    ALTER COLUMN "tenant_id" DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS "is_system"          boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS "is_privilege_admin" boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS "system_key"         citext;

-- One global row per built-in role (NULL system_key for tenant custom roles).
CREATE UNIQUE INDEX IF NOT EXISTS "uq_custom_roles_system_key"
    ON "public"."custom_roles" ("system_key") WHERE "system_key" IS NOT NULL;

